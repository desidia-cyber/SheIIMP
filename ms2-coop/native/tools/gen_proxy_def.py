#!/usr/bin/env python3
"""Generate the proxy .def for a DLL that takes over a system DLL's name.

A proxy is not optional about completeness.  Once our file is named `dxgi.dll`
inside the game's `Binaries\\Win64`, Windows resolves that name through the
executable's directory *before* System32, so every module in the process that
imports dxgi -- including System32's own `d3d11.dll` -- gets ours.  One missing
export becomes a loader failure in code we never touch.

So this enumerates the real DLL's exports and writes one forwarder per name.
Nothing is hand-maintained, so the list cannot drift from the DLL it mirrors.

The forwarder target is a full path into System32, which keeps the real DLL
exactly where Windows put it: no copy of a system binary is dropped next to the
game.  (If a path-qualified forwarder ever fails to resolve, the fallback is to
copy the real DLL beside ours under a second name and forward to that instead.)

Usage:
  python tools/gen_proxy_def.py --dll C:\\Windows\\System32\\dxgi.dll \
      --library dxgi --out mod/native/proxy.def
"""
import argparse
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pe_imports import PE  # noqa: E402


def read_exports(path):
    """-> (dll_name, [(name, ordinal, forwarder_or_None)])"""
    pe = PE(path)
    if not pe.ok:
        raise SystemExit("PARSE FAILED: %s" % "; ".join(pe.notes))
    with open(path, "rb") as fh:
        data = fh.read()

    exp_rva, exp_size = pe.dd[0]
    if exp_rva == 0:
        raise SystemExit("%s has no export directory" % path)
    off = pe.rva_to_off(exp_rva)
    (_c, _t, _ma, _mi, name_rva, base, nfunc, nname,
     addr_funcs, addr_names, addr_ords) = struct.unpack_from("<IIHHIIIIIII", data, off)

    nm = pe.rva_to_off(name_rva)
    dll_name = pe.cstr(nm) if nm is not None else "?"
    foff = pe.rva_to_off(addr_funcs)
    noff = pe.rva_to_off(addr_names)
    ooff = pe.rva_to_off(addr_ords)
    lo, hi = exp_rva, exp_rva + exp_size

    out = []
    for i in range(nname):
        (nrva,) = struct.unpack_from("<I", data, noff + i * 4)
        (ordinal,) = struct.unpack_from("<H", data, ooff + i * 2)
        (frva,) = struct.unpack_from("<I", data, foff + ordinal * 4)
        no = pe.rva_to_off(nrva)
        name = pe.cstr(no) if no is not None else None
        if not name:
            continue
        fwd = None
        if lo <= frva < hi:
            fo = pe.rva_to_off(frva)
            fwd = pe.cstr(fo) if fo is not None else None
        out.append((name, base + ordinal, fwd))
    return dll_name, out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dll", required=True)
    ap.add_argument("--library", required=True,
                    help="the internal name our proxy should report")
    ap.add_argument("--module", default=None,
                    help="forwarder module; defaults to the full path of --dll "
                         "minus its extension")
    ap.add_argument("--out", required=True)
    ap.add_argument("--header", default=None,
                    help="also emit a C header listing the export names, so the "
                         "proxy can self-check that every forwarder resolves")
    ap.add_argument("--cstubs", default=None,
                    help="also emit a C file defining a dummy symbol per export. "
                         "REQUIRED for link.exe: it resolves the forwarder's "
                         "right-hand symbol as a global and fails LNK2001 if "
                         "nothing defines it, even though the emitted export is a "
                         "real PE forwarder and no code from the stub is used.")
    args = ap.parse_args()

    dll_name, exports = read_exports(args.dll)
    module = args.module or os.path.splitext(os.path.abspath(args.dll))[0]

    exported_names = [n for n, _o, _f in exports]
    already = [n for n, _o, f in exports if f]

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="ascii", newline="\r\n") as fh:
        fh.write("; GENERATED by tools/gen_proxy_def.py -- DO NOT EDIT.\n")
        fh.write("; source module : %s\n" % args.dll)
        fh.write("; internal name : %s\n" % args.library)
        fh.write("; exports       : %d named\n" % len(exports))
        fh.write("; forwarder to  : %s\n" % module)
        fh.write("; All exports are re-exported so that modules which resolve this\n")
        fh.write("; DLL through the executable's directory keep working.\n")
        fh.write("LIBRARY %s\n" % args.library)
        fh.write("EXPORTS\n")
        for name, _ordinal, _fwd in exports:
            fh.write("    %s = %s.%s\n" % (name, module, name))

    print("wrote %s" % args.out)
    print("  source        : %s" % args.dll)
    print("  internal name : %s" % args.library)
    print("  exports       : %d" % len(exports))
    print("  forwarder to  : %s" % module)

    if args.header:
        os.makedirs(os.path.dirname(os.path.abspath(args.header)), exist_ok=True)
        with open(args.header, "w", encoding="utf-8", newline="\n") as fh:
            fh.write("// GENERATED by tools/gen_proxy_def.py -- DO NOT EDIT.\n")
            fh.write("// Export names taken from %s\n" % args.dll)
            fh.write("//\n")
            fh.write("// The proxy resolves every one of these at runtime and checks the\n")
            fh.write("// result lands back inside System32. A forwarder that fails to resolve\n")
            fh.write("// would otherwise show up only as a loader failure in some unrelated\n")
            fh.write("// module that imports this DLL later.\n")
            fh.write("#pragma once\n\n")
            fh.write("static const char* kExportNames[] = {\n")
            for name in exported_names:
                fh.write('    "%s",\n' % name)
            fh.write("};\n\n")
            fh.write("static const unsigned kExportCount =\n")
            fh.write("    sizeof(kExportNames) / sizeof(kExportNames[0]);\n")
        print("  header        : %s (%d names)" % (args.header, len(exported_names)))

    if args.cstubs:
        os.makedirs(os.path.dirname(os.path.abspath(args.cstubs)), exist_ok=True)
        with open(args.cstubs, "w", encoding="utf-8", newline="\n") as fh:
            fh.write("// GENERATED by tools/gen_proxy_def.py -- DO NOT EDIT.\n")
            fh.write("//\n")
            fh.write("// These definitions exist ONLY to satisfy link.exe.  Measured behaviour:\n")
            fh.write("// the linker resolves the symbol on the right of a .def forwarder as a\n")
            fh.write("// global and raises LNK2001 if nothing defines it, even though the export\n")
            fh.write("// it emits is a genuine PE forwarder with no code of ours behind it.\n")
            fh.write("//\n")
            fh.write("// Verified with tools/pe_export_table.py: the resulting DLL reports\n")
            fh.write("// 'forwarders: N  real code: 0', so none of these bodies is reachable.\n")
            fh.write("// They are declared C (no mangling) and include no headers, so they\n")
            fh.write("// cannot collide with a real declaration of the same name.\n")
            fh.write("\n")
            for name in exported_names:
                fh.write("void %s(void) {}\n" % name)
        print("  cstubs        : %s (%d stubs)" % (args.cstubs, len(exported_names)))
    if already:
        print("  NOTE: %d export(s) were themselves forwarders and are being "
              "re-forwarded: %s" % (len(already), ", ".join(already[:6])))
    if not exported_names:
        print("  ERROR: no exports found -- a proxy with no exports would break "
              "every importer")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
