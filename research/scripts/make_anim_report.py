#!/usr/bin/env python3
"""Turn slices/anim_catalog.csv into the step-8 report files.

Writes
  research/80-anim-catalog.md        method, rule table, summaries
  research/80-anim-catalog-part1.md  every AnimSequence
  research/80-anim-catalog-part2.md  every AnimMontage

All paths in the part files are written relative to /Game/Sparta/Characters/ to keep the
table readable; the full absolute paths are in slices/anim_catalog.csv.

Usage: python make_anim_report.py
"""
import collections
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RESEARCH = os.path.dirname(HERE)
CSV = os.path.join(RESEARCH, 'slices', 'anim_catalog.csv')
PREFIX = '/Game/Sparta/Characters/'

CATEGORY_NOTE = {
    'locomotion': 'walk/run/sprint/strafe/turn/jog sets',
    'attack': 'attacks, combos, heavy/light, plunge',
    'riposte': 'riposte / backstab-ish paired player+enemy anims',
    'hit': 'hit reactions, staggers, breaks',
    'death': 'death and death-pose anims',
    'dodge': 'dodge, dash, roll',
    'parry': 'parry / perfect block',
    'block': 'block / guard',
    'harden': 'harden / stone form',
    'cast': 'seal / spell / shell ability',
    'ranged': 'crossbow, ballistazooka, shotgun, sidearm, aiming',
    'traversal': 'jump, fall, land, climb, ladder',
    'interact': 'interact, pickup, loot, pray, kneel, sit, rest, emote, revive',
    'idle': 'idles and pre-aggro idles',
    'cinematic': 'intros, outros, story/shell-memory/cutscene anims',
    'vo': 'voice-over facial anims',
    'other': 'nothing matched (see the folder column)',
}


def load():
    rules = []
    rows = []
    with open(CSV, newline='', encoding='utf-8') as f:
        for rec in csv.reader(f):
            if rec and rec[0].startswith('# rule'):
                rules.append((rec[1], rec[2]))
                continue
            if not rec or rec[0].startswith('#'):
                continue
            if rec[0] == 'type':
                continue
            rows.append(rec)
    return rules, rows


def rel(path):
    return path[len(PREFIX):] if path.startswith(PREFIX) else path


def write_table(path, title, rows, intro):
    with open(path, 'w', encoding='utf-8') as f:
        f.write(title + '\n\n')
        f.write(intro + '\n\n')
        f.write('| # | category | character | asset | path (relative to `/Game/Sparta/Characters/`) | how |\n')
        f.write('|---:|---|---|---|---|---|\n')
        for i, (typ, cat, how, char, folder, name, full) in enumerate(rows, 1):
            f.write(f'| {i} | {cat} | {char} | {name} | {rel(full)} | {how} |\n')
    print(f'{path}: {len(rows)} rows')


def main():
    rules, rows = load()
    seq = [r for r in rows if r[0] == 'AnimSequence']
    mon = [r for r in rows if r[0] == 'AnimMontage']
    other_types = [r for r in rows if r[0] not in ('AnimSequence', 'AnimMontage')]

    counts = collections.Counter((r[0], r[1]) for r in rows)
    per_char = collections.Counter()
    for r in rows:
        if r[0] in ('AnimSequence', 'AnimMontage'):
            per_char[r[3]] += 1

    out = []
    w = out.append
    w('# 80 — Animation catalogue (`AnimSequence` / `AnimMontage` under `/Game/Sparta/Characters/`)')
    w('')
    w('Generated by `research\\scripts\\anim_catalog.py` from `raw\\index.sqlite3` (dump A, see '
      '`00-sources.md`), rendered by `scripts\\make_anim_report.py`. The full machine-readable '
      'table is `research\\slices\\anim_catalog.csv`; the same rows are laid out as markdown in '
      '`80-anim-catalog-part1.md` (AnimSequence) and `80-anim-catalog-part2.md` (AnimMontage).')
    w('')
    w('## Method')
    w('')
    w('```sql')
    w("SELECT type, path FROM obj WHERE type IN ('AnimSequence','AnimMontage') "
      "AND path LIKE '/Game/Sparta/Characters/%' ORDER BY path")
    w('```')
    w('')
    w('`category` is a **guess derived from the asset path**, never from playing the animation:')
    w('')
    w('1. the asset path is split into folder segments;')
    w('2. each rule is a set of *exact folder names*; the first rule (in the order printed below) '
      'that finds one of its names in the path wins;')
    w('3. if no folder rule matches, the asset **name** is tested against the same word list;')
    w('4. otherwise the row is `other`.')
    w('')
    w('The folder-name vocabulary was measured first (`scripts\\anim_folders.py` prints every folder '
      'segment under the prefix together with how many animation assets live under it), so the rule '
      'table uses names that actually occur in this game rather than guesses.')
    w('')
    w('**Deviation from the brief:** the brief suggested the buckets '
      '`locomotion/attack/dodge/hit/death/idle/interact/other`. The real folder tree has '
      'unambiguous folders that do not fit those seven (`Riposte` 290 assets, `VO` 131, '
      '`Parry`, `Block`, `Harden`, `Traversal`, `Cinematic`), so those got their own buckets and '
      'the `matched_by` column shows whether a row came from a folder (`folder`), from the asset '
      'name (`name`) or from nothing (`none`).')
    w('')
    w('Rule table (order = priority):')
    w('')
    w('| # | category | folder names | what it covers |')
    w('|---:|---|---|---|')
    for i, (cat, names) in enumerate(rules, 1):
        w(f'| {i} | {cat} | `{names}` | {CATEGORY_NOTE.get(cat, "")} |')
    w('')
    w('## Totals')
    w('')
    total_seq_mon = len(seq) + len(mon)
    w(f'`AnimSequence` + `AnimMontage` under the prefix: **{total_seq_mon}** '
      f'({len(seq)} sequences, {len(mon)} montages). '
      f'The same query also returned {len(other_types)} assets of other types '
      f'(BlendSpace, BlendSpace1D, PoseAsset, PhysicsAsset, Skeleton, AnimBlueprint, '
      f'AimOffsetBlendSpace); they are listed in `slices\\anim_catalog.csv` but not in the part files.')
    w('')
    w('### per type × category')
    w('')
    w('| type | category | count |')
    w('|---|---|---:|')
    for (typ, cat), n in sorted(counts.items()):
        if typ in ('AnimSequence', 'AnimMontage'):
            w(f'| {typ} | {cat} | {n} |')
    w('')
    w('`matched_by` distribution over all 5474 rows: '
      + ', '.join(f'{k}={v}' for k, v in sorted(collections.Counter(r[2] for r in rows).items())) + '.')
    w('')
    w('### per owning character folder (AnimSequence + AnimMontage)')
    w('')
    w('| character | count |')
    w('|---|---:|')
    for char, n in per_char.most_common():
        w(f'| {char} | {n} |')
    w('')
    w('## Notes that matter for a co-op mod')
    w('')
    w('* The shipped mod identifies a montage segment by *sequence path + position* at the sending '
      'client and plays the same `AnimSequence` on the receiving side (`docs\\HANDOFF.md` §10), so '
      'the asset paths in these tables are the identifiers that travel between clients.')
    w('* `_Montage`-suffixed assets are the montages built on the `A_*` sequence of the same name; '
      'both appear in the tables, which is why pairs are visible.')
    w('* `Shells\\_Shared\\Animation\\Locomotion\\` is the shared locomotion set used by the mod '
      '(`A_Shared_Idle_H`, `..._Walk_Fwd_H2`, `..._Sprint_800_H2`); per-shell and per-weapon '
      'locomotion lives in the same folder tree under each shell/weapon name.')
    w('* 220 rows were categorised from the asset *name* and 447 rows had no match at all '
      '(`other`/`vo` folders like `RBF`, `MH`, `SkMesh`, `Temp`); those are the ones to treat as '
      'unclassified.')
    w('')
    with open(os.path.join(RESEARCH, '80-anim-catalog.md'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(out))
    print('80-anim-catalog.md written')

    write_table(os.path.join(RESEARCH, '80-anim-catalog-part1.md'),
                '# 80 part 1 — every `AnimSequence` under `/Game/Sparta/Characters/`',
                seq,
                f'{len(seq)} rows. `category` is guessed from the path (see `80-anim-catalog.md` '
                'for the rule table); `how` says whether the path (`folder`) or the asset name '
                '(`name`) produced the category.')
    write_table(os.path.join(RESEARCH, '80-anim-catalog-part2.md'),
                '# 80 part 2 — every `AnimMontage` under `/Game/Sparta/Characters/`',
                mon,
                f'{len(mon)} rows. `category` is guessed from the path (see `80-anim-catalog.md` '
                'for the rule table); `how` says whether the path (`folder`) or the asset name '
                '(`name`) produced the category.')


if __name__ == '__main__':
    main()
