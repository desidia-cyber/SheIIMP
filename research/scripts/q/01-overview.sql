UNION ALL SELECT 'GA_ABP', COUNT(*) FROM obj WHERE type='Class' AND path LIKE '%/GA_%' AND path LIKE '/Game/%'
UNION ALL SELECT 'SaveObject', COUNT(*) FROM obj WHERE type='Class' AND path LIKE '%SaveObject%'
UNION ALL SELECT 'WorldState', COUNT(*) FROM obj WHERE type='Class' AND path LIKE '%WorldState%'
UNION ALL SELECT 'Door', COUNT(*) FROM obj WHERE type='Class' AND path LIKE '%Door%'
UNION ALL SELECT 'Chest', COUNT(*) FROM obj WHERE type='Class' AND path LIKE '%Chest%'
UNION ALL SELECT 'Checkpoint', COUNT(*) FROM obj WHERE type='Class' AND path LIKE '%Checkpoint%'
UNION ALL SELECT 'Bonfire', COUNT(*) FROM obj WHERE type='Class' AND path LIKE '%Bonfire%'
